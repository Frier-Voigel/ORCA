"""Pydantic models for shared contracts (plan.md Section 2).

Frozen in Phase 0. Source of truth for data shapes across Engine and Intelligence.
"""

from __future__ import annotations

from typing import Literal, Optional
from pydantic import BaseModel, ConfigDict, Field


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Graph
# ---------------------------------------------------------------------------

class Node(BaseModel):
    """A service node in the dependency graph."""
    model_config = ConfigDict(populate_by_name=True)

    id: str
    type: str
    criticality: float = Field(..., ge=0.0, le=1.0)


class Edge(BaseModel):
    """A directed dependency edge. source depends on target."""
    model_config = ConfigDict(populate_by_name=True)

    source: str
    target: str
    weight: float = Field(..., ge=0.0, le=1.0)
    kind: Literal["hard", "soft"]


class Graph(BaseModel):
    """Microservice dependency graph."""
    model_config = ConfigDict(populate_by_name=True)

    nodes: list[Node]
    edges: list[Edge]


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Metrics tick
# ---------------------------------------------------------------------------

class MetricTick(BaseModel):
    """One metrics row per service per simulation tick."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    service: str
    latency_p95_ms: float = Field(..., ge=0.0)
    error_rate: float = Field(..., ge=0.0, le=1.0)
    cpu: float = Field(..., ge=0.0, le=1.0)
    mem: float = Field(..., ge=0.0, le=1.0)
    queue_depth: int = Field(..., ge=0)
    status: Literal["healthy", "degraded", "failed"]


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Log line
# ---------------------------------------------------------------------------

class LogLine(BaseModel):
    """A structured log line generated by a service."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    service: str
    level: Literal["INFO", "WARN", "ERROR", "DEBUG"]
    message: str


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Failure prediction
# ---------------------------------------------------------------------------

class PredictionItem(BaseModel):
    """Failure prediction for an individual service."""
    model_config = ConfigDict(populate_by_name=True)

    service: str
    fail_prob: float = Field(..., ge=0.0, le=1.0)
    horizon_s: float = Field(..., ge=0.0)
    top_signals: list[str]


class PredictionResponse(BaseModel):
    """Predictions across services at a given timestamp."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    predictions: list[PredictionItem]


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Cascade forecast
# ---------------------------------------------------------------------------

class CascadePath(BaseModel):
    """A predicted path of cascading failure propagation."""
    model_config = ConfigDict(populate_by_name=True)

    from_node: str = Field(..., alias="from", serialization_alias="from")
    to_node: str = Field(..., alias="to", serialization_alias="to")
    prob: float = Field(..., ge=0.0, le=1.0)
    eta_s: float = Field(..., ge=0.0)


class CascadeForecast(BaseModel):
    """Cascade forecast showing paths and blast radius."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    paths: list[CascadePath]
    blast_radius: dict[str, int]


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Root cause
# ---------------------------------------------------------------------------

class RootCauseCandidate(BaseModel):
    """A ranked root cause candidate with confidence score and explanation."""
    model_config = ConfigDict(populate_by_name=True)

    service: str
    score: float = Field(..., ge=0.0, le=1.0)
    explanation: str


class RootCauseResponse(BaseModel):
    """Root cause ranking output."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    candidates: list[RootCauseCandidate]


# ---------------------------------------------------------------------------
# 2.4 Data shapes: Recovery options
# ---------------------------------------------------------------------------

class RecoveryOption(BaseModel):
    """A evaluated recovery strategy option."""
    model_config = ConfigDict(populate_by_name=True)

    strategy: str
    target: str
    services_saved: int = Field(..., ge=0)
    est_recovery_s: float = Field(..., ge=0.0)
    cost: float = Field(..., ge=0.0, le=1.0)
    risk: float = Field(..., ge=0.0, le=1.0)
    score: float = Field(..., ge=0.0, le=1.0)
    recommended: bool
    rationale: str
    projected_health: list[float]


class RecoveryResponse(BaseModel):
    """List of evaluated recovery options."""
    model_config = ConfigDict(populate_by_name=True)

    options: list[RecoveryOption]


# ---------------------------------------------------------------------------
# 2.5 Combined state (GET /api/state)
# ---------------------------------------------------------------------------

class FaultInfo(BaseModel):
    """Details of an injected or active fault."""
    model_config = ConfigDict(populate_by_name=True)

    service: str
    type: str


class IncidentState(BaseModel):
    """Incident status."""
    model_config = ConfigDict(populate_by_name=True)

    active: bool
    fault: Optional[FaultInfo] = None


class StateHistory(BaseModel):
    """Rolling history of failure probabilities for timeline charts."""
    model_config = ConfigDict(populate_by_name=True)

    fail_prob: dict[str, list[float]] = Field(default_factory=dict)


class SystemState(BaseModel):
    """Combined state payload returned by GET /api/state."""
    model_config = ConfigDict(populate_by_name=True)

    ts: float
    tick: int
    running: bool
    incident: IncidentState
    system_health: float = Field(..., ge=0.0, le=1.0)
    graph: Graph
    metrics: list[MetricTick]
    logs: list[LogLine]
    predictions: PredictionResponse
    cascade: CascadeForecast
    root_cause: RootCauseResponse
    recovery: RecoveryResponse
    history: StateHistory


# ---------------------------------------------------------------------------
# 2.6 Control endpoints
# ---------------------------------------------------------------------------

class InjectFaultRequest(BaseModel):
    """Payload for POST /api/inject-fault."""
    model_config = ConfigDict(populate_by_name=True)

    service: str
    type: str


class ApplyStrategyRequest(BaseModel):
    """Payload for POST /api/apply-strategy."""
    model_config = ConfigDict(populate_by_name=True)

    strategy: str
    target: str


class ControlRequest(BaseModel):
    """Payload for POST /api/control."""
    model_config = ConfigDict(populate_by_name=True)

    action: Literal["play", "pause"]
    speed: float = Field(default=1.0, gt=0.0)


class ResetResponse(BaseModel):
    """Response for POST /api/reset."""
    model_config = ConfigDict(populate_by_name=True)

    status: str = "reset"


class HealthResponse(BaseModel):
    """Response for GET /health."""
    model_config = ConfigDict(populate_by_name=True)

    status: str = "ok"


# ---------------------------------------------------------------------------
# 2.7 Simulator ground truth
# ---------------------------------------------------------------------------

class GroundTruth(BaseModel):
    """Ground truth output from simulator for evaluation and training."""
    model_config = ConfigDict(populate_by_name=True)

    root_cause: str
    fault_type: str
    onset_ts: float
    affected_services: list[str]
    failure_times: dict[str, float]


# Aliases for flexible naming across team modules
FailurePrediction = PredictionResponse
CascadeResponse = CascadeForecast
RootCause = RootCauseResponse
RecoveryPlan = RecoveryResponse
CombinedState = SystemState
